CREATE INDEX idx_entitlements_account ON entitlements(account_id, status);

CREATE TABLE billing_source_state (
  account_id TEXT NOT NULL REFERENCES accounts(id),
  source_ref TEXT NOT NULL,
  status TEXT NOT NULL,
  provider_event_created BIGINT,
  updated_at TEXT NOT NULL,
  PRIMARY KEY(account_id, source_ref)
);

CREATE TABLE checkout_claims (
  session_id TEXT PRIMARY KEY,
  account_id TEXT REFERENCES accounts(id),
  plan TEXT NOT NULL,
  tier TEXT,
  status TEXT NOT NULL,
  claimed_at TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE INDEX idx_checkout_claims_account ON checkout_claims(account_id, status);

CREATE TABLE checkout_intents (
  id TEXT PRIMARY KEY,
  account_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  plan TEXT NOT NULL,
  idempotency_key TEXT NOT NULL UNIQUE,
  stripe_session_id TEXT,
  checkout_url TEXT,
  status TEXT NOT NULL DEFAULT 'pending',
  expires_at TEXT,
