  leased_until TEXT,
  lease_token TEXT,
  last_error TEXT,
  idempotency_key TEXT UNIQUE,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  completed_at TEXT,
  CONSTRAINT jobs_payload_json_object CHECK (COALESCE(jsonb_typeof(payload_json::jsonb) = 'object', FALSE))
