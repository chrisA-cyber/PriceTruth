  metadata_json TEXT NOT NULL DEFAULT '{}',
  provider_event_created BIGINT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  UNIQUE(source, source_ref, product),
  CONSTRAINT entitlements_metadata_json_object CHECK (COALESCE(jsonb_typeof(metadata_json::jsonb) = 'object', FALSE))
